/**
 * Extracts the @unoff/ui component tokens of the Yelbolt theme into one
 * stylesheet, scoped to `.demo-kit` (the capability demos).
 *
 * The demos copy the web app's UI with these tokens instead of rendering
 * the @unoff/ui components: same values, but any state (hover, pressed,
 * selected…) can be shown on demand, and no component CSS or JS ships.
 *
 * Only the tokens the demos use are kept: the ones named in the kit and the
 * demos (USERS), plus the component tokens those refer to.
 *
 * Also writes the @unoff/ui spinner glyph alone (generated/unoff-spinner.css)
 * for the site's reveal motion: the rest of the app's icon set is not
 * shipped (the site and the demos use Lucide).
 *
 * Runs before `dev` and `build` (package.json); re-run after updating
 * @unoff/ui or using a new token: `npm run tokens`.
 *
 * Later (optimisation, not urgent): @unoff/ui binds its theme tokens to
 * `:root[data-theme=…]`, so this script rescopes them. If the library adds an
 * opt-in selector next to the existing one (`:root[data-theme=x],
 * [data-theme-scope][data-theme=x]`, no change for current apps), the platform
 * part can become plain imports + `data-theme-scope data-theme data-mode` on
 * the demo panel. Do not drop `:root` in the library: specificity side effects.
 */
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs'

import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

const pkgDir = join(root, 'node_modules/@unoff/ui')
const assets = join(pkgDir, 'dist/assets')
const { version } = JSON.parse(
  readFileSync(join(pkgDir, 'package.json'), 'utf8')
)

/** Component stylesheets whose tokens the demos use. */
const SOURCES = [
  'texts.css',
  'Chip.css',
  'ColorChip.css',
  'Button.css',
  'Input.css',
  'Dropdown.css',
  'Knob.css',
  'SimpleSlider.css',
  'MultipleSlider.css',
  'Bar.css',
  'SectionTitle.css',
  'SemanticMessage.css',
  'Message.css',
]

const read = (file) =>
  readFileSync(
    file === 'texts.css'
      ? join(assets, 'styles/texts/texts.css')
      : join(assets, file),
    'utf8'
  )

/** Files whose `--token` mentions decide what is kept. */
const USERS = [
  'src/styles/demo-kit.css',
  'src/components/capabilities',
  'src/scripts/demos',
]

const filesIn = (path) => {
  const full = join(root, path)
  try {
    return readdirSync(full, { recursive: true })
      .filter((name) => /\.(astro|ts|css)$/.test(name))
      .map((name) => join(full, name))
  } catch {
    return [full]
  }
}

const mentioned = new Set(
  USERS.flatMap(filesIn).flatMap((file) =>
    [...readFileSync(file, 'utf8').matchAll(/--[a-z0-9-]+/g)].map(([m]) => m)
  )
)

const toDeclarations = (body) =>
  body
    .split(';')
    .map((d) => d.trim())
    .filter(Boolean)
    .map((d) => {
      const at = d.indexOf(':')
      return { name: d.slice(0, at).trim(), value: d.slice(at + 1).trim() }
    })

const refsOf = (value) => [...value.matchAll(/--[a-z0-9-]+/g)].map(([m]) => m)

const header = `/* Generated by scripts/unoff-tokens.mjs from @unoff/ui ${version}. Do not edit. */\n`

/**
 * The component tokens of one @unoff/ui theme (`:root[data-theme=…]` blocks),
 * with the font family remapped: the library names the Google Fonts family,
 * the site self-hosts it.
 */
const themeTokens = (theme, fontFamily) =>
  SOURCES.map((file) => {
    const block = new RegExp(`:root\\[data-theme=${theme}\\]\\{([^}]*)\\}`, 'g')
    const declarations = [...read(file).matchAll(block)]
      .flatMap(([, body]) => toDeclarations(body))
      .map((d) =>
        d.name === '--text-font-family' ? { ...d, value: fontFamily } : d
      )
    if (!declarations.length) throw new Error(`No ${theme} tokens in ${file}`)
    return { file, declarations }
  })

/** Keep what is mentioned, then what kept tokens refer to (until stable). */
const keepFrom = (defined, seeds) => {
  const kept = new Set([...seeds].filter((name) => defined.has(name)))
  for (let grew = true; grew; ) {
    grew = false
    for (const name of [...kept])
      for (const ref of refsOf(defined.get(name).value))
        if (defined.has(ref) && !kept.has(ref)) {
          kept.add(ref)
          grew = true
        }
  }
  return kept
}

const lines = (declarations, kept) =>
  declarations
    .filter((d) => kept.has(d.name))
    .map((d) => `  ${d.name}: ${d.value};`)
    .join('\n')

const sectionsOf = (parsed, kept) =>
  parsed
    .map(({ file, declarations }) => {
      const body = lines(declarations, kept)
      return body ? `  /* ${file} */\n${body}` : ''
    })
    .filter(Boolean)
    .join('\n\n')

const write = (name, css) => {
  const out = join(root, 'src/styles/generated', name)
  mkdirSync(dirname(out), { recursive: true })
  writeFileSync(out, header + css)
  return out.replace(root + '/', '')
}

// ---- Yelbolt: the default look of every demo (.demo-kit). ----

const yelbolt = themeTokens('yelbolt', 'var(--font-text)')
const yelboltDefined = new Map(
  yelbolt.flatMap(({ declarations }) => declarations.map((d) => [d.name, d]))
)
const yelboltKept = keepFrom(yelboltDefined, mentioned)
console.log(
  `unoff tokens: ${yelboltKept.size}/${yelboltDefined.size} kept → ${write(
    'unoff-tokens.css',
    `.demo-kit {\n${sectionsOf(yelbolt, yelboltKept)}\n}\n`
  )}`
)

// ---- Platforms: the demos of a platform page wear that platform's UI. ----
//
// `[data-platform=figma] .demo-kit` swaps the component tokens to the Figma
// theme, and the Figma mode (light, or dark when the site is dark) supplies
// the colours they refer to, `--global-*` included. Each page imports its own
// file, so a platform costs nothing elsewhere.

const MODES = 'styles/tokens/modules'
const SITE_DARK = '[data-mode=yelbolt-uicp-dark]'

const PLATFORMS = {
  figma: { font: 'Inter', fontsource: 'inter' },
  penpot: { font: 'Work Sans', fontsource: 'work-sans' },
  sketch: { font: 'Inter', fontsource: 'inter' },
  framer: { font: 'Inter', fontsource: 'inter' },
}

/** Overrides of the kit's own aliases (demo-kit.css) for the platforms. */
const KIT_ALIASES = '  --k-panel-border: var(--global-border-color);'

const modeBlock = (platform, mode) => {
  const css = readFileSync(join(assets, MODES, `${platform}-modes.css`), 'utf8')
  const match = css.match(
    new RegExp(`(?:^|[};,])\\[data-mode=${platform}-${mode}\\]\\{([^}]*)\\}`)
  )
  if (!match) throw new Error(`No ${platform}-${mode} mode block`)
  return toDeclarations(match[1])
}

for (const [platform, { font, fontsource }] of Object.entries(PLATFORMS)) {
  const tokens = themeTokens(
    platform,
    `'${font} Variable', system-ui, sans-serif`
  )
  const defined = new Map(
    tokens.flatMap(({ declarations }) => declarations.map((d) => [d.name, d]))
  )
  const kept = keepFrom(defined, mentioned)

  // Colours: what the kept tokens and the kit refer to, in both modes.
  const seeds = new Set([
    ...mentioned,
    '--global-border-color',
    ...[...kept].flatMap((name) => refsOf(defined.get(name).value)),
  ])
  const modes = ['light', 'dark'].map((mode) => {
    const declarations = modeBlock(platform, mode)
    const modeDefined = new Map(declarations.map((d) => [d.name, d]))
    return lines(declarations, keepFrom(modeDefined, seeds))
  })

  const selector = `[data-platform=${platform}] .demo-kit`
  const file = write(
    `unoff-tokens-${platform}.css`,
    `@import '@fontsource-variable/${fontsource}/wght.css';\n\n` +
      `${selector} {\n${sectionsOf(tokens, kept)}\n\n  /* kit */\n${KIT_ALIASES}\n}\n\n` +
      `${selector} {\n  /* ${platform}-light */\n${modes[0]}\n}\n\n` +
      `${SITE_DARK} ${selector} {\n  /* ${platform}-dark */\n${modes[1]}\n}\n`
  )
  console.log(`unoff tokens (${platform}): ${kept.size} kept → ${file}`)
}

// The spinner of the reveal motion (motion.css), alone.
const icons = readFileSync(
  join(assets, 'styles/icons/styles/yelbolt.css'),
  'utf8'
)
const spinner = icons.match(/--icon-spinner:\s*(url\("[^"]*"\))/)
if (!spinner) throw new Error('No --icon-spinner in the Yelbolt icon set')
writeFileSync(
  join(root, 'src/styles/generated/unoff-spinner.css'),
  `/* Generated by scripts/unoff-tokens.mjs from @unoff/ui ${version}. Do not edit. */\n` +
    `:root {\n  --icon-spinner: ${spinner[1]};\n}\n`
)
